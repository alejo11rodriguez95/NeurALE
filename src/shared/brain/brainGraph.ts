/**
 * Grafo del "cerebro" del Núcleo Neuronal, repartido en sus dos hemisferios.
 *
 * Los nodos y conexiones se muestrearon proceduralmente dentro del contorno de un
 * cerebro (vista frontal), descartando la franja central y sin permitir que ninguna
 * conexión cruzara de un lado al otro. Por eso el cerebro se puede dividir en dos
 * mitades clicables sin regenerar nada: son los mismos 120 nodos y las mismas
 * 204 conexiones de siempre, solo repartidos.
 *
 * Cada hemisferio trae su mitad del contorno como un path CERRADO (el corte es una
 * recta sobre el eje, que queda oculta dentro del canal de la fisura). Al renderizar,
 * cada mitad se desplaza hacia afuera del eje para abrir ese canal — ver `BrainCore`.
 *
 * Sistema de coordenadas: viewBox "-118 -112 236 186".
 */

export interface BrainHemisphere {
  /** Contorno cerrado de la mitad: sirve de relleno, de trazo y de área clicable. */
  outline: string
  /** Cuerpos neuronales [x, y] de esa mitad. */
  nodes: readonly (readonly [number, number])[]
  /** Conexiones, como pares de índices dentro de `nodes` de esa misma mitad. */
  edges: readonly (readonly [number, number])[]
  /** Índices (dentro de `nodes`) de los nodos destacados que laten. */
  hubs: readonly number[]
}

